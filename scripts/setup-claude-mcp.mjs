#!/usr/bin/env node
/**
 * One-time setup: builds the MCP server and configures Claude Desktop + Cursor.
 *
 * Usage:
 *   node scripts/setup-claude-mcp.mjs
 *
 * You will need:
 *   - Node.js 18+ with npm (https://nodejs.org)
 *   - An API key from RemoAsset → Admin → API Keys (starts with ra_)
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { execSync } from 'child_process';
import { homedir, platform } from 'os';
import { join, resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import readline from 'readline';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mcpDir = join(root, 'mcp-server');
const mcpEntry = join(mcpDir, 'dist', 'index.js');

function log(msg) {
  console.log(`\n✓ ${msg}`);
}

function fail(msg) {
  console.error(`\n✗ ${msg}`);
  process.exit(1);
}

function readEnvFile(path) {
  if (!existsSync(path)) return {};
  const out = {};
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eq = trimmed.indexOf('=');
    if (eq === -1) continue;
    out[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim().replace(/^["']|["']$/g, '');
  }
  return out;
}

function findNpm() {
  const candidates = ['npm', '/opt/homebrew/bin/npm', '/usr/local/bin/npm'];
  for (const cmd of candidates) {
    try {
      execSync(`${cmd} --version`, { stdio: 'pipe' });
      return cmd;
    } catch {
      /* try next */
    }
  }
  return null;
}

async function prompt(question) {
  const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
  return new Promise((resolve) => {
    rl.question(question, (answer) => {
      rl.close();
      resolve(answer.trim());
    });
  });
}

function mergeMcpConfig(existing, serverName, serverConfig) {
  const config = existing && typeof existing === 'object' ? existing : {};
  config.mcpServers = config.mcpServers ?? {};
  config.mcpServers[serverName] = serverConfig;
  return config;
}

function writeJson(path, data) {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, JSON.stringify(data, null, 2) + '\n', 'utf8');
}

async function main() {
  console.log('\n══════════════════════════════════════════════════');
  console.log('  RemoAsset Connect → Claude MCP Setup');
  console.log('══════════════════════════════════════════════════\n');

  // Step 1: npm
  const npm = findNpm();
  if (!npm) {
    fail(
      'npm not found. Install Node.js 18+ from https://nodejs.org then run this script again.'
    );
  }
  log(`Found npm (${execSync(`${npm} --version`, { encoding: 'utf8' }).trim()})`);

  // Step 2: build MCP server
  console.log('\nBuilding MCP server (first time may take a minute)...');
  execSync(`${npm} install`, { cwd: mcpDir, stdio: 'inherit' });
  execSync(`${npm} run build`, { cwd: mcpDir, stdio: 'inherit' });

  if (!existsSync(mcpEntry)) {
    fail(`Build failed — expected ${mcpEntry}`);
  }
  log('MCP server built');

  // Step 3: API URL + key
  const env = {
    ...readEnvFile(join(root, '.env')),
    ...readEnvFile(join(mcpDir, '.env')),
  };

  let apiUrl = process.env.REMOASSET_API_URL || env.REMOASSET_API_URL || env.VITE_SUPABASE_URL;
  if (apiUrl && !apiUrl.includes('/functions/v1/api')) {
    apiUrl = `${apiUrl.replace(/\/$/, '')}/functions/v1/api`;
  }

  if (!apiUrl || apiUrl.includes('YOUR_PROJECT')) {
    apiUrl = await prompt(
      'Enter your Supabase project URL (e.g. https://abc123.supabase.co): '
    );
    apiUrl = `${apiUrl.replace(/\/$/, '')}/functions/v1/api`;
  }

  let apiKey = process.env.REMOASSET_API_KEY || env.REMOASSET_API_KEY;
  if (!apiKey || apiKey.includes('YOUR')) {
    console.log('\nCreate an API key in RemoAsset: Admin → API Keys → Create');
    console.log('(Or Developer page → API Keys)\n');
    apiKey = await prompt('Paste your API key (starts with ra_): ');
  }

  if (!apiKey.startsWith('ra_')) {
    fail('API key should start with ra_ — check you copied the full key from Admin.');
  }

  log('Credentials ready');

  const serverConfig = {
    command: 'node',
    args: [mcpEntry],
    env: {
      REMOASSET_API_URL: apiUrl,
      REMOASSET_API_KEY: apiKey,
    },
  };

  // Step 4: Write mcp-server/.env for reference
  writeFileSync(
    join(mcpDir, '.env'),
    `# Auto-generated by setup-claude-mcp.mjs — do not commit\nREMOASSET_API_URL=${apiUrl}\nREMOASSET_API_KEY=${apiKey}\n`,
    'utf8'
  );
  log('Saved mcp-server/.env');

  // Step 5: Claude Desktop config
  const claudeConfigPath =
    platform() === 'darwin'
      ? join(homedir(), 'Library', 'Application Support', 'Claude', 'claude_desktop_config.json')
      : platform() === 'win32'
        ? join(process.env.APPDATA || join(homedir(), 'AppData', 'Roaming'), 'Claude', 'claude_desktop_config.json')
        : join(homedir(), '.config', 'Claude', 'claude_desktop_config.json');

  let claudeExisting = {};
  if (existsSync(claudeConfigPath)) {
    try {
      claudeExisting = JSON.parse(readFileSync(claudeConfigPath, 'utf8'));
    } catch {
      claudeExisting = {};
    }
  }
  const claudeConfig = mergeMcpConfig(claudeExisting, 'remoasset-connect', serverConfig);
  writeJson(claudeConfigPath, claudeConfig);
  log(`Claude config written: ${claudeConfigPath}`);

  // Step 6: Cursor project config
  const cursorDir = join(root, '.cursor');
  mkdirSync(cursorDir, { recursive: true });
  writeJson(join(cursorDir, 'mcp.json'), mergeMcpConfig({}, 'remoasset-connect', serverConfig));
  log('Cursor config written: .cursor/mcp.json');

  console.log('\n══════════════════════════════════════════════════');
  console.log('  Setup complete!');
  console.log('══════════════════════════════════════════════════');
  console.log('\nNext steps:');
  console.log('  1. Deploy the latest API (one time):');
  console.log('       supabase functions deploy api');
  console.log('  2. Quit Claude completely and reopen it');
  console.log('  3. In Claude, ask: "Use remoasset_help — what can you do?"');
  console.log('\nExample prompts:');
  console.log('  • "Search leads with status Qualified"');
  console.log('  • "Create a task due tomorrow for John"');
  console.log('  • "List pending client requests"');
  console.log('  • "Transfer lead X to Sarah"\n');
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
